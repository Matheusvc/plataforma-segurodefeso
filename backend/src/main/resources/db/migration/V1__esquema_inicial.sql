-- Esquema inicial da plataforma Seguro-Defeso (PostgreSQL e H2 em modo PostgreSQL).

CREATE TABLE usuarios (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(150) NOT NULL,
    email        VARCHAR(200) NOT NULL UNIQUE,
    senha_hash   VARCHAR(200) NOT NULL,
    papel        VARCHAR(20)  NOT NULL,
    ativo        BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em    TIMESTAMP    NOT NULL,
    ultimo_login TIMESTAMP
);

CREATE TABLE login_tentativas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email   VARCHAR(200) NOT NULL,
    momento TIMESTAMP    NOT NULL,
    sucesso BOOLEAN      NOT NULL
);
CREATE INDEX idx_login_email ON login_tentativas (email, momento);

CREATE TABLE config (
    chave VARCHAR(60)  PRIMARY KEY,
    valor VARCHAR(500) NOT NULL
);

CREATE TABLE clientes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                 VARCHAR(200) NOT NULL,
    cpf                  VARCHAR(11)  NOT NULL UNIQUE,
    nit                  VARCHAR(30),
    nascimento           DATE,
    telefone             VARCHAR(40),
    endereco             VARCHAR(300),
    municipio            VARCHAR(120),
    colonia              VARCHAR(120),
    rgp_numero           VARCHAR(60),
    rgp_desde            VARCHAR(20),
    rgp_validade         DATE,
    especie              VARCHAR(120),
    procuracao_validade  DATE,
    gov_nivel            VARCHAR(10),
    honorarios_pct       NUMERIC(5, 2),
    etapa                VARCHAR(20)  NOT NULL,
    protocolo            VARCHAR(60),
    situacao             VARCHAR(500),
    exigencia_texto      VARCHAR(500),
    prazo_data           DATE,
    indeferimento_motivo VARCHAR(500),
    ciencia_data         DATE,
    parcelas_total       INTEGER      NOT NULL DEFAULT 0,
    parcelas_liberadas   INTEGER      NOT NULL DEFAULT 0,
    ultima_conferencia   DATE,
    observacoes          VARCHAR(2000),
    ativo                BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em            TIMESTAMP    NOT NULL,
    atualizado_em        TIMESTAMP    NOT NULL
);
CREATE INDEX idx_clientes_etapa ON clientes (etapa);

CREATE TABLE requisitos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT      NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    chave      VARCHAR(30) NOT NULL,
    atende     BOOLEAN,
    CONSTRAINT uq_requisito UNIQUE (cliente_id, chave)
);

CREATE TABLE documentos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id    BIGINT       NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    tipo          VARCHAR(30)  NOT NULL,
    competencia   VARCHAR(7),
    nome_original VARCHAR(255) NOT NULL,
    arquivo       VARCHAR(100) NOT NULL,
    tamanho       BIGINT       NOT NULL,
    enviado_por   BIGINT REFERENCES usuarios (id),
    enviado_em    TIMESTAMP    NOT NULL
);
CREATE INDEX idx_documentos_cliente ON documentos (cliente_id);

CREATE TABLE dae (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id    BIGINT      NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    competencia   VARCHAR(7)  NOT NULL,
    valor_venda   NUMERIC(12, 2),
    valor_dae     NUMERIC(12, 2),
    status        VARCHAR(20) NOT NULL,
    atualizado_em TIMESTAMP   NOT NULL,
    CONSTRAINT uq_dae UNIQUE (cliente_id, competencia)
);

CREATE TABLE defesos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    especie            VARCHAR(120) NOT NULL,
    regiao             VARCHAR(300),
    portaria           VARCHAR(60),
    inicio             DATE         NOT NULL,
    fim                DATE,
    prazo_requerimento DATE         NOT NULL,
    criado_em          TIMESTAMP    NOT NULL
);

CREATE TABLE honorarios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT         NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    valor            NUMERIC(12, 2) NOT NULL,
    data_recebimento DATE           NOT NULL,
    observacao       VARCHAR(300),
    usuario_id       BIGINT REFERENCES usuarios (id)
);

CREATE TABLE eventos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES clientes (id) ON DELETE CASCADE,
    usuario_id BIGINT REFERENCES usuarios (id),
    momento    TIMESTAMP    NOT NULL,
    tipo       VARCHAR(30)  NOT NULL,
    descricao  VARCHAR(1000) NOT NULL
);
CREATE INDEX idx_eventos_cliente ON eventos (cliente_id);
